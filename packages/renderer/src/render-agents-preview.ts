import {spawn} from 'node:child_process';
import {createHash} from 'node:crypto';
import {mkdir,readFile,writeFile,access} from 'node:fs/promises';
import {resolve} from 'node:path';
import {validateEditorialStoryboard} from '../../shared/src/editorial-storyboard.js';
import {ffmpegPath,probe,run} from './media-tools.js';
import {validateVideoQa} from './video-qa.js';

const dir=resolve('data/agents100');
const raw=resolve(dir,'agents-0-30-raw.mp4');
const final=resolve(dir,'agents-0-30.mp4');
const fixture=resolve('fixtures/storyboards/toolpilot-agents-100s.json');
const remotion=resolve('node_modules/@remotion/cli/remotion-cli.js');
const storyboard=validateEditorialStoryboard(JSON.parse(await readFile(fixture,'utf8')));
await mkdir(dir,{recursive:true});
await mkdir(resolve('public/generated'),{recursive:true});
const tick=resolve('public/generated/agents-tick.wav');
const rate=48000;
const samples=Buffer.alloc(Math.floor(rate*.33)*2);
for(let i=0;i<samples.length/2;i++){
  const t=i/rate;
  const envelope=Math.exp(-t*23);
  const signal=Math.sin(2*Math.PI*(720-440*t)*t)*.35*envelope;
  samples.writeInt16LE(Math.round(signal*32767),i*2);
}
const header=Buffer.alloc(44);
header.write('RIFF',0);header.writeUInt32LE(36+samples.length,4);header.write('WAVEfmt ',8);
header.writeUInt32LE(16,16);header.writeUInt16LE(1,20);header.writeUInt16LE(1,22);
header.writeUInt32LE(rate,24);header.writeUInt32LE(rate*2,28);header.writeUInt16LE(2,32);
header.writeUInt16LE(16,34);header.write('data',36);header.writeUInt32LE(samples.length,40);
await writeFile(tick,Buffer.concat([header,samples]));
for(const asset of [resolve('public',storyboard.narration.previewAudioPath),resolve('public/generated/agents-tick.wav')]) await access(asset);
const runVisible=(command:string,args:string[])=>new Promise<void>((ok,fail)=>{const child=spawn(command,args,{stdio:'inherit'});child.once('error',fail);child.once('close',code=>code===0?ok():fail(new Error(`${command} exited ${code}`)));});
await runVisible(process.execPath,[remotion,'render','remotion/index.ts','ToolPilotAgents30s',raw,'--codec=h264','--crf=18','--pixel-format=yuv420p','--concurrency=4','--overwrite']);
const pass1=await run(ffmpegPath,['-hide_banner','-nostats','-i',raw,'-map','0:a:0','-af','loudnorm=I=-16:TP=-1.5:LRA=11:print_format=json','-f','null','-']);
const match=pass1.stderr.match(/\{\s*"input_i"[\s\S]*?\}/);
if(!match) throw new Error('FFmpeg loudnorm measurement missing');
const m=JSON.parse(match[0]);
await run(ffmpegPath,['-hide_banner','-loglevel','error','-y','-i',raw,'-map','0:v:0','-map','0:a:0','-c:v','copy','-af',`loudnorm=I=-16:TP=-1.5:LRA=11:measured_I=${m.input_i}:measured_LRA=${m.input_lra}:measured_TP=${m.input_tp}:measured_thresh=${m.input_thresh}:offset=${m.target_offset}:linear=true`,'-c:a','aac','-b:a','192k','-ar','48000','-movflags','+faststart',final]);
const p=await probe(final);
const checks=validateVideoQa(p,{durationMs:30000,width:1920,height:1080,fps:30,minAudioChannels:1}).checks;
const after=await run(ffmpegPath,['-hide_banner','-nostats','-i',final,'-map','0:a:0','-af','loudnorm=I=-16:TP=-1.5:LRA=11:print_format=json','-f','null','-']);
const lm=after.stderr.match(/\{\s*"input_i"[\s\S]*?\}/);
const loudness=lm?JSON.parse(lm[0]):null;
checks.push({id:'loudness',label:'Integrated loudness',passed:!!loudness&&Math.abs(Number(loudness.input_i)+16)<=1.5,detail:loudness?.input_i??'missing'});
checks.push({id:'captions',label:'Timed captions',passed:storyboard.narration.captions.length>0&&storyboard.narration.captions.at(-1)!.endMs<30000,detail:`${storyboard.narration.captions.length} cues`});
const stamp=(ms:number)=>{const h=Math.floor(ms/3600000),m=Math.floor(ms/60000)%60,s=Math.floor(ms/1000)%60,part=ms%1000;return `${String(h).padStart(2,'0')}:${String(m).padStart(2,'0')}:${String(s).padStart(2,'0')},${String(part).padStart(3,'0')}`};
await writeFile(resolve(dir,'agents-0-30.srt'),storyboard.narration.captions.map((c,i)=>`${i+1}\n${stamp(c.startMs)} --> ${stamp(c.endMs)}\n${c.text}\n`).join('\n'));
await run(ffmpegPath,['-hide_banner','-loglevel','error','-y','-i',final,'-vf','fps=1/3,scale=384:-1,tile=5x2:padding=8:margin=8:color=0x101820','-frames:v','1',resolve(dir,'contact-sheet.png')]);
const hash=createHash('sha256').update(await readFile(final)).digest('hex');
const qa={passed:checks.every(c=>c.passed),checks,probe:p,loudness,sha256:hash,reviewStatus:'proposed',renderedRangeMs:[0,30000],storyboard:fixture};
await writeFile(resolve(dir,'qa.json'),JSON.stringify(qa,null,2));
await writeFile(resolve(dir,'asset-manifest.json'),JSON.stringify({assets:storyboard.assets.filter(a=>a.usage==='0-30s'),narration:{provider:storyboard.narration.provider,voice:storyboard.narration.voice,source:'Gemini Flash TTS via existing adapter',raw:resolve(dir,'narration-raw.wav')},sfx:{source:'original synthesized tick',path:'public/generated/agents-tick.wav'}},null,2));
console.log(`Output: ${final}\nQA: ${checks.filter(c=>c.passed).length}/${checks.length} passed\nSHA-256: ${hash}`);
if(!qa.passed) process.exitCode=1;
